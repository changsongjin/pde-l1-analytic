"""Grammar-closed maximal weak library with L1/IRL1.

New experiment only. Existing scripts are intentionally left unchanged.

The library is finite by construction: all weak-form-compatible terms
generated by the grammar in ``build_terms`` are included.  For each fixed
lambda, ``LazyL1`` solves the L1 problem on an active subset and adds omitted
columns that violate the L1 KKT condition.  When the scan is exhausted, the
solution is the full-library L1 solution for that lambda.
"""

from __future__ import annotations

import argparse
import json
import platform
import time
from pathlib import Path

import numpy as np
from numpy.polynomial import polynomial as Poly
from scipy.signal import correlate

import noise_inverse as N
import noise_inverse_biglib as B
from lasso_exact import lars_lasso_path, lasso_at


SUPPORT_TOL = 1e-5
P_TEST = 8
MAX_POWER = 8
MAX_DERIV = 6
TRIG_FREQ = 3
TRIG_DERIV = 4
COORD_MAX_DEG = 2
COORD_POWER = {1: 8, 2: 4}
COORD_DERIV = {1: 4, 2: 3}
EXP_SCALE = 2
EXP_DERIV = 3
INV_POWER = 2
INV_DERIV = 3
INCLUDE_NONPOLY = False
N_LAMBDA = 24
LAMBDA_MIN_RATIO = 1e-6
IRL1_RATIO = 1e-3
IRL1_EPS = 1e-8
IRL1_MAX_ITER = 8
KKT_TOL = 1e-9


def _term(family, *, m=0, k=0, a=0, sign=1):
    return {"family": family, "m": int(m), "k": int(k), "a": int(a), "sign": int(sign)}


def build_terms(include_nonpoly=INCLUDE_NONPOLY):
    """Generate the finite weak-form grammar used in this experiment."""
    terms = [_term("const")]
    for m in range(1, MAX_POWER + 1):
        for k in range(MAX_DERIV + 1):
            terms.append(_term("pow", m=m, k=k))
    if include_nonpoly:
        for family in ("sin", "cos"):
            for m in range(1, TRIG_FREQ + 1):
                for k in range(TRIG_DERIV + 1):
                    terms.append(_term(family, m=m, k=k))
    for a in range(1, COORD_MAX_DEG + 1):
        for m in range(1, COORD_POWER[a] + 1):
            for k in range(COORD_DERIV[a] + 1):
                terms.append(_term("coord_pow", m=m, k=k, a=a))
    if include_nonpoly:
        for sign in (-1, 1):
            for m in range(1, EXP_SCALE + 1):
                for k in range(EXP_DERIV + 1):
                    terms.append(_term("exp", m=m, k=k, sign=sign))
        for m in range(1, INV_POWER + 1):
            for k in range(INV_DERIV + 1):
                terms.append(_term("inv", m=m, k=k))
    return terms


def term_name(term):
    f, m, k, a, sign = (term[x] for x in ("family", "m", "k", "a", "sign"))
    if f == "const":
        return "1"
    if f == "pow":
        base = "u" if m == 1 else f"u^{m}"
    elif f in ("sin", "cos"):
        base = f"{f}(u)" if m == 1 else f"{f}({m}u)"
    elif f == "coord_pow":
        base = "x u" if m == 1 else f"x u^{m}"
        if a == 2:
            base = "x^2 u" if m == 1 else f"x^2 u^{m}"
    elif f == "exp":
        base = f"exp({sign * m}u)"
    elif f == "inv":
        base = f"(1+u^2)^(-{m})"
    else:
        raise ValueError(f)
    if k == 0:
        return base
    if f == "pow" and m == 1:
        return "u_" + "x" * k
    return f"({base})_" + "x" * k


def term_complexity(term):
    f, m, k, a = term["family"], term["m"], term["k"], term["a"]
    return 1 + k + m + 2 * a + (2 if f in ("exp", "inv") else 0)


def _base_field(term, u, xx):
    f, m, a, sign = term["family"], term["m"], term["a"], term["sign"]
    if f == "const":
        return np.ones_like(u)
    if f == "pow":
        field = u ** m
    elif f == "sin":
        field = np.sin(m * u)
    elif f == "cos":
        field = np.cos(m * u)
    elif f == "coord_pow":
        field = (xx ** a) * (u ** m)
    elif f == "exp":
        field = np.exp(sign * m * u)
    elif f == "inv":
        field = (1.0 + u * u) ** (-m)
    else:
        raise ValueError(f)
    return field


def make_data(case, sigma, seed, terms):
    """Build weak-form design matrix for a case and noisy observation."""
    rng = np.random.default_rng(seed)
    x = np.linspace(*case["x"])
    t = np.linspace(*case["t"])
    dx, dt = x[1] - x[0], t[1] - t[0]
    tt, xx = np.meshgrid(t, x, indexing="ij")
    hx, ht = case["half"]
    max_k = max(term["k"] for term in terms)

    def bump(n_half, h, max_d):
        s = np.linspace(-1.0, 1.0, 2 * n_half + 1)
        a = n_half * h
        poly = Poly.polypow([1.0, 0.0, -1.0], P_TEST)
        out, q = [], poly
        for d in range(max_d + 1):
            out.append(Poly.polyval(s, q) / a ** d)
            q = Poly.polyder(q)
        return out

    px = bump(hx, dx, max_k)
    pt = bump(ht, dt, 2)
    blocks_a, blocks_b = [], []

    for fn in case["traj"]:
        u0 = fn(xx.ravel(), tt.ravel()).reshape(xx.shape)
        u = u0 + sigma * np.std(u0) * rng.standard_normal(u0.shape)

        def integ(field, kx, kt=0):
            kernel = np.outer(pt[kt], px[kx])
            full = correlate(field, kernel, mode="valid", method="fft") * dx * dt
            return full[::ht, ::hx].ravel()

        cols = []
        for term in terms:
            cols.append((-1) ** term["k"] * integ(_base_field(term, u, xx), term["k"], 0))
        if case["target"] == "u_tt":
            cols.append(-integ(u, 0, 1))
            b = integ(u, 0, 2)
        else:
            b = -integ(u, 0, 1)
        a = np.column_stack(cols)
        scale = max(float(np.linalg.norm(b)), 1e-15)
        blocks_a.append(a / scale)
        blocks_b.append(b / scale)

    a = np.vstack(blocks_a)
    b = np.concatenate(blocks_b)
    names = [term_name(t) for t in terms]
    if case["target"] == "u_tt":
        names.append("u_t")
    return a, b, names, {"x": list(case["x"]), "t": list(case["t"]), "rows": int(a.shape[0])}


class LazyL1:
    """Full-library L1 through active-set KKT column generation."""

    def __init__(self, a, b, names, seed_terms=None):
        raw_norm = np.linalg.norm(a, axis=0)
        self.valid = raw_norm > 1e-13
        self.a = a[:, self.valid] / np.maximum(raw_norm[self.valid], 1e-300)
        self.names = [n for n, ok in zip(names, self.valid) if ok]
        self.b = np.asarray(b, dtype=float)
        self.p = self.a.shape[1]
        self.seed_terms = set(seed_terms or range(min(12, self.p)))
        self.dot_b = self.a.T @ self.b

    def lambda_max(self, weights=None):
        w = np.ones(self.p) if weights is None else np.asarray(weights)
        return float(np.max(np.abs(self.dot_b) / np.maximum(w, 1e-300)))

    def solve_fixed(self, lam, weights, active, max_rounds=30):
        weights = np.asarray(weights, dtype=float)
        active = set(int(i) for i in active if 0 <= i < self.p)
        history = []
        for _ in range(max_rounds):
            idx = sorted(active)
            if idx:
                knots = lars_lasso_path(self.a[:, idx], self.b, weights[idx], lam_min_ratio=0.0)
                beta_active = lasso_at(knots, float(lam))
                beta = np.zeros(self.p)
                beta[idx] = beta_active
            else:
                beta = np.zeros(self.p)
            residual = self.b - self.a @ beta
            gap = np.abs(self.a.T @ residual) - float(lam) * weights
            gap[list(active)] = -np.inf
            add = np.where(gap > KKT_TOL * max(1.0, float(lam)))[0]
            if add.size == 0:
                history.append({"active": len(active), "added": 0, "max_omitted_gap": float(np.max(gap))})
                return beta, history
            order = add[np.argsort(gap[add])[::-1]]
            add = order[: min(8, order.size)]
            active.update(int(i) for i in add)
            history.append({"active": len(active), "added": int(add.size), "max_omitted_gap": float(np.max(gap[add]))})
        raise RuntimeError("KKT column generation did not converge")

    def path_supports(self, weights=None, n_lambda=N_LAMBDA):
        weights = np.ones(self.p) if weights is None else np.asarray(weights, dtype=float)
        lam_max = self.lambda_max(weights)
        active = set(self.seed_terms)
        supports, solves = [], []
        for ratio in np.geomspace(1.0, LAMBDA_MIN_RATIO, n_lambda):
            lam = lam_max * float(ratio)
            beta, hist = self.solve_fixed(lam, weights, active)
            active.update(int(i) for i in np.where(np.abs(beta) > SUPPORT_TOL)[0])
            supports.append(tuple(int(i) for i in np.where(np.abs(beta) > SUPPORT_TOL)[0]))
            solves.append({"lambda": float(lam), "support": list(supports[-1]), "history": hist})
        return supports, solves

    def irl1_supports(self):
        weights = np.ones(self.p)
        outer = []
        beta = np.zeros(self.p)
        for it in range(IRL1_MAX_ITER):
            lam = self.lambda_max(weights) * IRL1_RATIO
            beta, hist = self.solve_fixed(lam, weights, self.seed_terms)
            supp = tuple(int(i) for i in np.where(np.abs(beta) > SUPPORT_TOL)[0])
            outer.append({"iter": it, "lambda": float(lam), "support": list(supp), "history": hist})
            new_weights = 1.0 / (np.abs(beta) + IRL1_EPS)
            if it and supp == tuple(outer[-2]["support"]):
                weights = new_weights
                break
            weights = new_weights
        supports, path = self.path_supports(weights)
        return supports, {"outer": outer, "path": path, "weights": weights.tolist()}


def support_eval(a, b, support, names, true):
    if not support:
        coef = np.zeros(0)
    else:
        coef = np.linalg.lstsq(a[:, list(support)], b, rcond=None)[0]
    got = [names[i] for i in support]
    true_set = set(true)
    got_set = set(got)
    true_coef = np.array([true[k] for k in true], dtype=float)
    coef_map = dict(zip(got, coef))
    err = np.sqrt(sum((coef_map.get(k, 0.0) - v) ** 2 for k, v in true.items()) / max(float(true_coef @ true_coef), 1e-300))
    return {"support": got, "exact": got_set == true_set, "extra": len(got_set - true_set),
            "missed": len(true_set - got_set), "coef_rel_err": float(err)}


def choose_support(problem, supports):
    criterion = N.Criterion(problem.a, problem.b)
    best = criterion.best(supports)
    return best, criterion


def run_one(case, sigma, seed, terms):
    a, b, names, meta = make_data(case, sigma, seed, terms)
    p = LazyL1(a, b, names)
    valid_names = p.names
    true = {k: v for k, v in case["true"].items() if k in valid_names}
    if len(true) != len(case["true"]):
        raise RuntimeError(f"true term missing from maximal grammar: {case['true']}")
    t0 = time.perf_counter()
    supports_l1, trace_l1 = p.path_supports()
    s_l1, cr_l1 = choose_support(p, supports_l1)
    l1_time = time.perf_counter() - t0
    t0 = time.perf_counter()
    supports_i, trace_i = p.irl1_supports()
    s_i, cr_i = choose_support(p, supports_i)
    irl1_time = time.perf_counter() - t0
    t0 = time.perf_counter()
    cr_s = N.Criterion(p.a, p.b)
    s_s = N.m_stridge(cr_s)
    stridge_time = time.perf_counter() - t0
    out = {
        "case": case["pde"], "sigma": sigma, "seed": seed, "library_size": int(len(names)),
        "valid_library_size": int(p.p), "n_rows": meta["rows"], "library": names,
        "methods": {
            "GML1": {**support_eval(p.a, p.b, s_l1, valid_names, true), "time_s": l1_time,
                     "criterion_calls": cr_l1.calls, "path_support_count": len(supports_l1)},
            "GML1_IRL1": {**support_eval(p.a, p.b, s_i, valid_names, true), "time_s": irl1_time,
                          "criterion_calls": cr_i.calls, "path_support_count": len(supports_i)},
            "PDE-FIND_STRidge": {**support_eval(p.a, p.b, s_s, valid_names, true), "time_s": stridge_time,
                                 "criterion_calls": cr_s.calls},
        },
        "traces": {"GML1": trace_l1, "GML1_IRL1": trace_i},
        "true": case["true"],
    }
    return out


def load_external_reference():
    root = Path(__file__).parent
    out = {}
    for name in ("sga_compare_result.json", "sga_compare_extra_result.json"):
        path = root / name
        if path.exists():
            try:
                out[name] = json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                out[name] = {"error": "invalid JSON"}
    return out


def get_cases(kind):
    cases = dict(N.CASES)
    if kind in ("biglib", "all"):
        cases.update(B.CASES)
    return cases


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", choices=("baseline", "biglib", "all"), default="baseline")
    ap.add_argument("--noise", nargs="+", type=float, default=[0.0, 0.01, 0.03, 0.05, 0.07, 0.10])
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--nonpoly", action="store_true", help="also include sin/cos/exp/inverse weak terms")
    ap.add_argument("--output", default=None)
    args = ap.parse_args()
    terms = build_terms(include_nonpoly=args.nonpoly)
    cases = get_cases(args.cases)
    if args.only:
        cases = {k: v for k, v in cases.items() if k in args.only}
    if args.smoke:
        cases = {next(iter(cases)): next(iter(cases.values()))}
        args.noise = [0.0, 0.05]
        args.seeds = 1

    report = {
        "python": platform.python_version(), "numpy": np.__version__,
        "method": "GML-L1: grammar-closed maximal weak library + KKT-certified lazy L1 column generation",
        "solver": "exact L1 via LARS on active columns; IRL1 uses w=1/(|beta|+eps); STRidge is PDE-FIND control",
        "grammar": {
            "max_power": MAX_POWER, "max_derivative": MAX_DERIV, "trig_frequency": TRIG_FREQ,
            "trig_derivative": TRIG_DERIV, "coordinate_max_degree": COORD_MAX_DEG,
            "coordinate_power": COORD_POWER, "coordinate_derivative": COORD_DERIV,
            "exp_scale": EXP_SCALE, "inverse_power": INV_POWER,
            "include_nonpoly": args.nonpoly,
            "n_generated_terms": len(terms), "terms": [term_name(t) for t in terms],
            "weak_form_note": "D_x^k(x^a f(u)) is evaluated by moving derivatives to the test function; derivative products are a later jet-library extension.",
        },
        "noise": args.noise, "n_seeds": args.seeds, "support_tol": SUPPORT_TOL,
        "cases": {}, "external_reference": load_external_reference(),
    }

    for cname, case in cases.items():
        rows = []
        for sigma in args.noise:
            seeds = [0] if sigma == 0 else list(range(args.seeds))
            agg = {m: {"exact": 0, "extra": 0, "missed": 0, "errs": [], "time": 0.0, "calls": 0, "supports": {}}
                   for m in ("GML1", "GML1_IRL1", "PDE-FIND_STRidge")}
            raw = []
            for seed in seeds:
                one = run_one(case, sigma, seed, terms)
                raw.append(one)
                for m, ev in one["methods"].items():
                    g = agg[m]
                    g["exact"] += int(ev["exact"])
                    g["extra"] += ev["extra"]
                    g["missed"] += ev["missed"]
                    g["errs"].append(ev["coef_rel_err"])
                    g["time"] += ev["time_s"]
                    g["calls"] += ev.get("criterion_calls", 0)
                    key = " + ".join(ev["support"])
                    g["supports"][key] = g["supports"].get(key, 0) + 1
            row = {"sigma": sigma, "n": len(seeds), "raw": raw}
            for m, g in agg.items():
                row[m] = {
                    "exact_rate": g["exact"] / len(seeds), "mean_extra": g["extra"] / len(seeds),
                    "mean_missed": g["missed"] / len(seeds), "coef_rel_err_median": float(np.median(g["errs"])),
                    "mean_time_s": g["time"] / len(seeds), "mean_criterion_calls": g["calls"] / len(seeds),
                    "supports": dict(sorted(g["supports"].items(), key=lambda kv: -kv[1])[:5]),
                }
            rows.append(row)
            print(cname, "sigma", sigma, {m: row[m]["exact_rate"] for m in agg}, flush=True)
        report["cases"][cname] = {"pde": case["pde"], "true": case["true"], "rows": rows}

    out = Path(args.output) if args.output else Path(__file__).with_name("gml1_maxlib_compare_result.json")
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
